import type { CategoriaId, Empresa, NivelIntegracaoId } from '../types'

type Draft = {
  id: string
  slug: string
  nome: string
  razao?: string
  telefone?: string
  email?: string
  site?: string
  cidade: string
  uf: string
  endereco: string
  numero?: string
  bairro?: string
  cep?: string
  lat: number
  lng: number
  categoria: CategoriaId
  sub: string[]
  tags: string[]
  nivel?: NivelIntegracaoId
  especialidades: string[]
  apresentacao: string
  servicos: string[]
  area: string
  fonte: string
  fonteUrl: string
}

function pub(d: Draft): Empresa {
  return {
    id: d.id,
    slug: d.slug,
    razao_social: d.razao ?? d.nome,
    nome_fantasia: d.nome,
    telefone: d.telefone,
    email: d.email,
    site_url: d.site,
    cidade: d.cidade,
    uf: d.uf,
    endereco: d.endereco,
    numero: d.numero,
    bairro: d.bairro,
    cep: d.cep,
    lat: d.lat,
    lng: d.lng,
    categoria: d.categoria,
    subcategorias: d.sub,
    tags: d.tags,
    nivel_integracao: d.nivel,
    especialidades: d.especialidades,
    apresentacao: d.apresentacao,
    servicos_intro: d.apresentacao,
    servicos: d.servicos,
    area_atuacao: d.area,
    cobertura: `${d.endereco}${d.numero ? `, ${d.numero}` : ''} — ${d.cidade}/${d.uf}`,
    origem: 'publico',
    fontes: [{ titulo: d.fonte, url: d.fonteUrl }],
  }
}

