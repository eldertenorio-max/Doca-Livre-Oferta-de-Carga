import type { CategoriaId, Empresa } from '../types'

function pub(d: {
  id: string
  slug: string
  nome: string
  site?: string
  cidade: string
  uf: string
  lat: number
  lng: number
  categoria: CategoriaId
  sub: string[]
  tags: string[]
  especialidades: string[]
  apresentacao: string
  servicos: string[]
  area: string
  fonte?: string
  fonteUrl?: string
}): Empresa {
  return {
    id: d.id,
    slug: d.slug,
    razao_social: d.nome,
    nome_fantasia: d.nome,
    site_url: d.site,
    cidade: d.cidade,
    uf: d.uf,
    endereco: d.cidade,
    lat: d.lat,
    lng: d.lng,
    categoria: d.categoria,
    subcategorias: d.sub,
    tags: d.tags,
    especialidades: d.especialidades,
    apresentacao: d.apresentacao,
    servicos_intro: d.apresentacao,
    servicos: d.servicos,
    area_atuacao: d.area,
    cobertura: `${d.cidade}/${d.uf}`,
    origem: 'publico',
    fontes: [{ titulo: d.fonte ?? d.nome, url: d.fonteUrl ?? d.site ?? 'https://www.gov.br/' }],
  }
}

