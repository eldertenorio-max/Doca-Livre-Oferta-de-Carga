type Ponto = readonly [cidade: string, uf: string]

type Rede = {
  prefixo: string
  nome: string
  razao: string
  matrizId: string
  categoria: CategoriaId
  sub: string[]
  tags: string[]
  nivel: NivelIntegracaoId
  site: string
  fonte: string
  fonteUrl: string
  skip: Ponto[]
  pontos: Ponto[]
}

function chave(cidade: string, uf: string) {
  return `${cidade}|${uf}`
}

function slugParte(s: string) {
  return s
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
}

function filiaisDaRede(rede: Rede): Empresa[] {
  const skip = new Set(rede.skip.map(([cidade, uf]) => chave(cidade, uf)))
  const vistos = new Set<string>()
  const lista: Empresa[] = []

  for (const [cidade, uf] of rede.pontos) {
    const k = chave(cidade, uf)
    if (skip.has(k) || vistos.has(k)) continue
    vistos.add(k)
    const xy = C[k]
    if (!xy) throw new Error(`Falta coordenada de ${cidade}/${uf}`)
    const slug = `${slugParte(rede.nome)}-${slugParte(cidade)}-${uf.toLowerCase()}`
    lista.push({
      id: `${rede.prefixo}-${slugParte(cidade)}-${uf.toLowerCase()}`,
      slug,
      razao_social: rede.razao,
      nome_fantasia: `${rede.nome} — ${cidade}`,
      site_url: rede.site,
      cidade,
      uf,
      endereco: cidade,
      lat: xy[0],
      lng: xy[1],
      categoria: rede.categoria,
      subcategorias: rede.sub,
      tags: [...rede.tags, 'filial', slugParte(rede.nome)],
      nivel_integracao: rede.nivel,
      especialidades: rede.sub.slice(0, 3),
      apresentacao: `Filial da ${rede.nome} em ${cidade}/${uf}, listada na página oficial de unidades.`,
      servicos_intro: `Unidade em ${cidade}/${uf}.`,
      servicos: rede.sub,
      area_atuacao: `${cidade}/${uf}.`,
      cobertura: `${cidade}/${uf}`,
      origem: 'publico',
      papel_hierarquia: 'filial_operador',
      hierarquia_superior: rede.matrizId,
      fontes: [{ titulo: rede.fonte, url: rede.fonteUrl }],
    })
  }
  return lista
}

